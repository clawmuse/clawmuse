import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { format } from "oxfmt";

// Share the website's editable identity and raster export dependency.
const require = createRequire(new URL("../packages/website/package.json", import.meta.url));
const sharp = require("sharp");
const root = new URL("../", import.meta.url);
const { symbol } = JSON.parse(
  readFileSync(new URL("packages/website/clawmuse/identity.json", root), "utf8"),
);
const paths = symbol.paths.map(({ d }) => `<path d="${d}"/>`).join("");
const strokes = `fill="none" stroke-width="${symbol.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"`;
const symbolSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${symbol.viewBox}" ${strokes} stroke="black">${paths}</svg>`;

function icon({
  background = "#102827",
  color = "#8de0bf",
  radius = 24,
  inset = 7,
  badge = "",
} = {}) {
  const width = 96 - inset * 2;
  const height = (width * 64) / 82;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="96" height="96" viewBox="0 0 96 96"><rect width="96" height="96" rx="${radius}" fill="${background}"/><svg x="${inset}" y="${(96 - height) / 2}" width="${width}" height="${height}" viewBox="${symbol.viewBox}" ${strokes} stroke="${color}">${paths}</svg>${badge}</svg>`;
}

function png(svg, size) {
  return sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
}

function macIcon(images) {
  const chunks = images.map(([type, data]) => {
    const header = Buffer.alloc(8);
    header.write(type);
    header.writeUInt32BE(data.length + 8, 4);
    return Buffer.concat([header, data]);
  });
  const header = Buffer.alloc(8);
  header.write("icns");
  header.writeUInt32BE(8 + chunks.reduce((size, chunk) => size + chunk.length, 0), 4);
  return Buffer.concat([header, ...chunks]);
}

function windowsIcon(images) {
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(([size, data], index) => {
    const entry = 6 + index * 16;
    header[entry] = size === 256 ? 0 : size;
    header[entry + 1] = header[entry];
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map(([, data]) => data)]);
}

export async function syncBrandAssets({ check, brand }) {
  function output(file, contents) {
    const target = new URL(file, root);
    const bytes = Buffer.from(contents);
    if (check) {
      if (!readFileSync(target).equals(bytes)) throw new Error(`Stale branding: ${file}`);
    } else writeFileSync(target, bytes);
  }
  const symbolModule = "packages/app/src/components/icons/brand-symbol.generated.ts";
  const source = `// Generated by npm run branding:sync from the website identity.\nexport const brandSymbol = ${JSON.stringify(symbol)} as const;\nexport const brandSymbolSvg = ${JSON.stringify(symbolSvg)};\n`;
  const { code, errors } = await format(symbolModule, source, { printWidth: 100 });
  if (errors.length) throw new Error("Invalid generated brand symbol");
  output(symbolModule, code);
  const manifestPath = "packages/app/public/manifest.json";
  const manifest = JSON.parse(readFileSync(new URL(manifestPath, root), "utf8"));
  manifest.name = brand.name;
  manifest.short_name = brand.name;
  const manifestOutput = await format(manifestPath, JSON.stringify(manifest), { printWidth: 100 });
  output(manifestPath, manifestOutput.code);
  const htmlPath = "packages/app/public/index.html";
  const html = readFileSync(new URL(htmlPath, root), "utf8");
  output(
    htmlPath,
    html.replace(
      /(<meta name="apple-mobile-web-app-title" content=")[^"]*(" \/>)/,
      `$1${brand.name}$2`,
    ),
  );
  const app = "packages/app/assets/images";
  const publicDir = "packages/app/public";
  const desktop = "packages/desktop/assets";
  const appIcon = icon({ radius: 0, inset: 16 });
  const desktopIcon = icon();
  for (const [file, size] of [
    [`${app}/icon.png`, 1024],
    [`${publicDir}/apple-touch-icon.png`, 180],
    [`${publicDir}/pwa-icon-192.png`, 192],
    [`${publicDir}/pwa-icon-512.png`, 512],
  ])
    output(
      file,
      await sharp(Buffer.from(appIcon)).resize(size, size).removeAlpha().png().toBuffer(),
    );
  output(
    `${app}/android-icon-foreground.png`,
    await png(icon({ background: "none", inset: 22 }), 1024),
  );
  output(
    `${app}/notification-icon.png`,
    await png(icon({ background: "none", color: "white" }), 96),
  );
  output(`${app}/splash-icon.png`, await png(desktopIcon, 200));
  output(`${app}/favicon.png`, await png(desktopIcon, 48));
  for (const [scheme, background, color] of [
    ["light", "#102827", "#8de0bf"],
    ["dark", "#8de0bf", "#102827"],
  ]) {
    for (const status of ["", "-running", "-attention"]) {
      const badgeColor = status === "-running" ? "#22c55e" : "#f59e0b";
      const badge = status
        ? `<circle cx="78" cy="78" r="15" fill="${badgeColor}" stroke="${background}" stroke-width="5"/>`
        : "";
      const svg = icon({ background, color, badge });
      output(`${app}/favicon-${scheme}${status}.svg`, `${svg}\n`);
      output(`${app}/favicon-${scheme}${status}.png`, await png(svg, 48));
    }
  }
  for (const [file, size] of [
    ["icon.png", 512],
    ["32x32.png", 32],
    ["64x64.png", 64],
    ["128x128.png", 128],
    ["128x128@2x.png", 256],
  ])
    output(`${desktop}/${file}`, await png(desktopIcon, size));
  const devBadge =
    '<circle cx="78" cy="78" r="13" fill="#f59e0b" stroke="#102827" stroke-width="4"/>';
  output(`${desktop}/icon-dev.png`, await png(icon({ badge: devBadge }), 512));
  const mac = [];
  for (const [type, size] of [
    ["icp4", 16],
    ["icp5", 32],
    ["icp6", 64],
    ["ic07", 128],
    ["ic08", 256],
    ["ic09", 512],
    ["ic10", 1024],
  ])
    mac.push([type, await png(desktopIcon, size)]);
  output(`${desktop}/icon.icns`, macIcon(mac));
  const windows = [];
  for (const size of [16, 24, 32, 48, 64, 128, 256])
    windows.push([size, await png(desktopIcon, size)]);
  output(`${desktop}/icon.ico`, windowsIcon(windows));
}
