import { format } from "oxfmt";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const BRAND_PACKAGES = ["app", "desktop", "server", "cli"];

/** Writes `packages/<pkg>/src/brand.generated.ts` under `root` from `brand`. */
export async function writeBrandModules({ root, brand, check = false }) {
  for (const pkg of BRAND_PACKAGES) {
    const rawOutput = `// Generated by npm run branding:sync. Edit branding/brand.json.\nexport const brand = ${JSON.stringify(
      brand,
      null,
      2,
    )
      .replace(/"([a-zA-Z]+)":/g, "$1:")
      .replace(/\n}/, ",\n}")} as const;\n`;
    const target = path.join(root, "packages", pkg, "src", "brand.generated.ts");
    const { code: output, errors } = await format(target, rawOutput, { printWidth: 100 });
    if (errors.length) throw new Error(`Invalid generated branding: ${pkg}`);
    if (check) {
      if (readFileSync(target, "utf8") !== output) throw new Error(`Stale branding: ${pkg}`);
    } else writeFileSync(target, output);
  }
}
