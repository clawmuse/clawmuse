import { format } from "oxfmt";
import { readFileSync, writeFileSync } from "node:fs";
const brand = JSON.parse(readFileSync(new URL("../branding/brand.json", import.meta.url), "utf8"));
for (const pkg of ["app", "desktop", "server", "cli"]) {
  const rawOutput = `// Generated by npm run branding:sync. Edit branding/brand.json.\nexport const brand = ${JSON.stringify(
    brand,
    null,
    2,
  )
    .replace(/"([a-zA-Z]+)":/g, "$1:")
    .replace(/\n}/, ",\n}")} as const;\n`;
  const target = new URL(`../packages/${pkg}/src/brand.generated.ts`, import.meta.url);
  const { code: output, errors } = await format(target.pathname, rawOutput, { printWidth: 100 });
  if (errors.length) throw new Error(`Invalid generated branding: ${pkg}`);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) throw new Error(`Stale branding: ${pkg}`);
  } else writeFileSync(target, output);
}
